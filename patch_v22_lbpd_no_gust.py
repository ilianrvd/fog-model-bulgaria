# -*- coding: utf-8 -*-
"""
patch_v22_lbpd_no_gust.py  —  LBPD излиза от поривния режимен критерий
=======================================================================
Пипа САМО run_case.py (AIRPORT_CONFIG). verify_cases.py не се променя —
той чете конфигурацията от run_case.

Закръгля линията v20 → v21 → v22. Механизмът на кръпката остава
(gust_thresholds работи и е тестван); маха се само прилагането му при
Пловдив.

════════════════════════════════════════════════════════════════════
ХРОНОЛОГИЯ И ДАННИ
════════════════════════════════════════════════════════════════════

v20 (27.07) включи gust_regime за LBGO и LBPD.
    LBGO   CSI 0.393 → 0.407   MAE_T 2.29 → 2.17   ← остава
    LBPD   CSI 0.316 → 0.316   MAE_T 2.53 → 2.60   ← нулева полза
    Две MAE_T регресии, и двете LBPD DYNM.

v21 вдигна поривния праг на LBPD от 8 на 12 kt. НУЛЕВ ЕФЕКТ —
    нито един променен случай. Причина: критерият действа в две
    посоки, а щетата идваше през ИЗЛИЗАНЕТО:
        влизане:  V >= V_thr И G >= G_thr   → DYNAMIC
        излизане: V <  V_thr И G <  G_thr   → RADIATIVE
    Вдигането на прага прави излизането ПО-ЛЕСНО. При
    LBPD_DYNM_2024-11-04, 20 UTC: V=1.0 kt, G=3.7 kt — и при 8, и при
    12 kt двете са под прага, форсира RADIATIVE еднакво. Оттам
    свободното охлаждане до 0.1 °C при реални 8 °C, MAE_T 1.82 → 4.51.

ЗАЩО СЕ МАХА
------------
Не заради регресиите, а защото цели грешната причина. Разбор на
единайсетте FA при Пловдив по наблюдаваната облачност (scan_metar_
clouds.py, само нощните часове 18-08 UTC):

    6 случая  средно 7.5-8.0 октас  — облачни нощи
    5 случая  средно 0.0-4.9 октас  — ясни нощи (всичките CDRY)
    1-2       биха се повлияли от поривния праг

Тоест критерият адресира най-малката от трите популации.

ЗАЩО LBGO ОСТАВА
----------------
Там ползата е измерена и в двете посоки: CSI +0.014, MAE_T сума
−5.62 върху 4 променени случая, включително LBGO_DYNM_2024-10-03 —
случаят, който породи цялата линия — с −0.86. Нула засегнати HIT
в решетъчния скан.

ЗА ПРОТОКОЛА: ОБЛАЧНАТА ХИПОТЕЗА Е ОТХВЪРЛЕНА ЗА ЦЕЛИЯ МОДЕЛ
------------------------------------------------------------
Разбор по височинни пояси (scan_metar_clouds2.py), пояс ВИСОКА
(основа >= 2000 ft, където облак не може да е самата мъгла),
FA срещу CN:

    LBBG  0.00 / 1.13      LBGO  1.65 / 3.51
    LBSF  2.11 / 3.31      LBWN  0.00 / 2.08
    LBPD  3.34 / 2.56   ← единственото изключение

В четири от пет летища ФАЛШИВИТЕ ТРЕВОГИ СТАВАТ В ПО-ЯСНИ НОЩИ ОТ
ЧИСТИТЕ ОТРИЦАНИЯ — обратното на облачната хипотеза. Ако ICON
разчистваше облаци и това причиняваше фалшивото охлаждане, FA
нощите щяха да са наблюдавано по-облачни.

При LBPD разликата е в пояс СРЕДНА (500-2000 ft): FA 1.63 срещу
CN 0.21 — ниски стратуси, локално явление, не покривка.

СЛЕДВАЩИЯТ ПРИОРИТЕТ Е ВЛАГАТА, НЕ ОБЛАЦИТЕ
-------------------------------------------
24 от 41 FA са CDRY, при Tmin_err +0.51 (моделът е по-ТОПЪЛ).
Фалшива мъгла в ясни сухи нощи при точна температура → влажностен
бюджет. Съвпада с LBWN 2024-09-23: T точна до 0.2 K, консервираният
qv изисква RH≈94 %, моделът обявява 99.5 %.
"""
import io, os, shutil, sys

PATH = "run_case.py"

OLD = (
    "    # gust_thresholds (V_kt, Gust_kt) — по подразбиране (4.0, 8.0).\r\n"
    "    # LBPD е на 12 kt порив: скан 27.07 показва, че при 8 kt критерият\r\n"
    "    # докосва 12 CN нощи, за да хване 2 FA (шест към едно), и произвежда\r\n"
    "    # температурни регресии в ясните нощи. При 12 kt: 1 FA, 3 CN, 0 HIT.\r\n"
    "    # ICON вятърът в Тракийската низина е ПОДценен (LBPD 2024-11-04:\r\n"
    "    # ICON 2.4-3.7 kt при METAR 8-10 kt), затова ниският праг пуска\r\n"
    "    # RADIATIVE твърде рано. ПРЕДВАРИТЕЛНА стойност — калибрирана върху\r\n"
    "    # 1 FA + 3 CN случая; преразглежда се при разширен набор.\r\n"
    "    \"LBPD\": {\"coastal\": False, \"gust_regime\": True, "
    "\"gust_thresholds\": (4.0, 12.0), \"N_d\": 200e6, \"tau_T\": 3600,  "
    "\"tau_qv\": 10800, \"sst_month\": None},\r\n"
)

NEW = (
    "    # gust_thresholds (V_kt, Gust_kt) — по подразбиране (4.0, 8.0).\r\n"
    "    # Механизмът е наличен и тестван; засега никое летище не го\r\n"
    "    # предефинира.\r\n"
    "    #\r\n"
    "    # LBPD БЕЗ gust_regime (v22, 27.07.2026). Опитано и отхвърлено:\r\n"
    "    #   v20 (праг 8):  CSI 0.316 → 0.316, MAE_T 2.53 → 2.60, 2 регресии\r\n"
    "    #   v21 (праг 12): нула променени случая — критерият действа в две\r\n"
    "    #     посоки и вдигането на прага прави ИЗЛИЗАНЕТО по-лесно, а\r\n"
    "    #     щетата идваше оттам (2024-11-04, 20 UTC: V=1.0 kt, G=3.7 kt\r\n"
    "    #     са под всеки праг → форсира RADIATIVE → MAE_T 1.82 → 4.51)\r\n"
    "    #\r\n"
    "    # Причината да се махне не са регресиите, а че цели грешната\r\n"
    "    # популация. Разбор на 11-те FA по наблюдавана облачност:\r\n"
    "    #   6 облачни нощи · 5 ясни (всичките CDRY) · 1-2 вятърни\r\n"
    "    \"LBPD\": {\"coastal\": False, \"N_d\": 200e6, \"tau_T\": 3600,  "
    "\"tau_qv\": 10800, \"sst_month\": None},\r\n"
)


def main():
    if not os.path.exists(PATH):
        sys.exit(f"[!] Няма {PATH}.")
    with io.open(PATH, "r", encoding="utf-8", newline="") as f:
        src = f.read()
    if src.count(OLD) != 1:
        sys.exit(f"[!] Очаквах 1 съвпадение, намерих {src.count(OLD)}. "
                 f"Приложени ли са v20 и v21? Нищо не е променено.")
    shutil.copy2(PATH, PATH + ".bak_v22")
    with io.open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(src.replace(OLD, NEW))
    print(f"[OK] {PATH}  копие: {PATH}.bak_v22")

    # проверка
    import ast, re
    s = io.open(PATH, encoding="utf-8").read()
    m = re.search(r"AIRPORT_CONFIG = \{(.*?)\n\}", s, re.S).group(1)
    cfg = ast.literal_eval("{" + m + "}")
    print()
    for k, v in cfg.items():
        print(f"  {k}: gust_regime={str(v.get('gust_regime', False)):5} "
              f"прагове={v.get('gust_thresholds', (4.0, 8.0))}")
    on = {k for k, v in cfg.items() if v.get("gust_regime")}
    assert on == {"LBWN", "LBBG", "LBGO"}, f"неочаквано: {on}"
    print()
    print("[OK] поривният критерий: LBWN, LBBG, LBGO")
    print("[!]  Пусни пълния петлетищен гейт.")


if __name__ == "__main__":
    main()
