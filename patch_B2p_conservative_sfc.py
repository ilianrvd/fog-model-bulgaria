# -*- coding: utf-8 -*-
"""
patch_B2p_conservative_sfc.py  —  консервативно свързване повърхност-колона
===========================================================================
ПРОМЕНЯ ФИЗИКАТА ДЪЛБОКО. Пипа turbulent_diffusion(), __init__ и SEB
блока в step(). Засяга T, qv, ql и TKE.

Заменя отхвърлената B2 (само граничното условие), която срина CSI
0.384 → 0.034. Причината за онзи срив е установена и е адресирана тук.

════════════════════════════════════════════════════════════════════
ДВАТА ДЕФЕКТА СА ЕДИН
════════════════════════════════════════════════════════════════════

(1) turbulent_diffusion, редове 687-689: коментарът казва Neumann,
    кодът прави Дирихле — b[0]=1, c[0]=0 при d[0]=phi[0] дава
    phi_new[0]=phi[0], ЗАМРАЗЕНА СТОЙНОСТ. Операторът не запазва
    колонния интеграл; замразеното ниво храни съседа си вечно.

(2) step(), ред 926-930: повърхностният поток се внася само в клетка 0,
    но с ΔT, сметнато за слой DZ_EFF (8/50/500 m), докато клетката е
    дебела dz_full[0] ≈ 0.11 m. Реално внесената енергия е
    dz_full[0]/DZ_EFF ≈ 1.3 % от H_sfc·dt.

Поотделно всеки изглежда като катастрофа. Заедно се компенсират —
фиктивното внасяне (1.3 %) и фиктивното размножаване (замразената
клетка като безкраен резервоар) се събират до нещо близко до 100 %.
Затова моделът с два дефекта работеше, а с един поправен — не.

НО КОМПЕНСАЦИЯТА НЕ Е УСТОЙЧИВА. Измерено, отношение предадено/
теоретично при постоянен поток −15 W/m²:

    K m²/s   30 стъпки    60     180
    0.005      0.30      0.42    0.71
    0.030      0.76      1.04    1.76
    0.300      2.74      3.65    6.06

Двайсеткратен разброс. А в мъгления клон (DZ_EFF=50) при реалистични
K до колоната стига 7–32 % от повърхностния поток — още една, дотук
неизвестна причина мъглата да не може да се задълбочи.

Тоест няма старо поведение, което да се пази. Има шум, приеман за
настройка.

════════════════════════════════════════════════════════════════════
ПРОМЯНАТА
════════════════════════════════════════════════════════════════════

A) turbulent_diffusion: истински Neumann (нулев поток) и на двете
   стени, с обмен със съседното ниво.

Б) SEB внасянето: същото ΔT се прилага на ВСИЧКИ нива в слоя
   DZ_EFF, не само на нулевото, и се нормира по действителната
   дебелина на слоя:

       ΔT = H_sfc·dt / (ρ·cp·Σ dz_full[слой])
       T_new[слой] += ΔT

   Тогава внесената енергия е ρ·cp·ΔT·Σdz = H_sfc·dt точно.
   Същото за росата с E_dew.

   DZ_EFF запазва смисъла си — дълбочина, в която повърхностният
   поток се усеща — но вече е консервативен. Стойностите 8/50/500
   НЕ се пипат в тази кръпка.

   Причината да не се прави flux гранично условие в самия решател:
   seb_step се извиква СЛЕД дифузията в step(), тоест H_sfc не е
   известен по време на решаването. Разпределянето по слоя е
   операторно разцепване на същото нещо и не изисква пренареждане
   на step().

════════════════════════════════════════════════════════════════════
ПРИЕМАТЕЛЕН ТЕСТ (изпълнява се от самата кръпка след прилагане)
════════════════════════════════════════════════════════════════════
Отношението предадено/теоретично трябва да е 1.000 за всички
K ∈ {0.005, 0.03, 0.3}, за 30/60/180 стъпки и за трите клона на
DZ_EFF. Постигнато при разработката:

    B2′  всички комбинации → 1.000

════════════════════════════════════════════════════════════════════
ОЧАКВАНО
════════════════════════════════════════════════════════════════════
Мъгленият клон ще получава 3–14× повече охлаждане, отколкото досега.
Ясният клон — между 0.3× и 6× в зависимост от K, тоест по-скоро
по-малко при слабо смесване. Гейтът ще се разклати силно.

Възможно е DZ_EFF стойностите (8/50/500) да поискат повторна
калибровка, защото са настройвани срещу неконсервативната система.
Това е очаквано и не е сигнал за грешна посока — но е отделна
стъпка, с отделен гейт.
"""
import io, os, shutil, subprocess, sys

PATH = "fog_model.py"

# ── A. Гранични условия ───────────────────────────────────────────────
OLD_BC = (
    "    # Гранични условия (Neumann - нулев поток)\r\n"
    "    b[0] = 1.0;  c[0] = 0.0\r\n"
    "    a[-1] = 0.0; b[-1] = 1.0\r\n"
)
NEW_BC = (
    "    # ── B2′ (27.07.2026): ИСТИНСКИ Neumann — нулев поток през стените ──\r\n"
    "    # Беше: b[0]=1; c[0]=0; a[-1]=0; b[-1]=1 — което при d[0]=phi[0]\r\n"
    "    # дава phi_new[0]=phi[0], тоест ЗАМРАЗЕНА СТОЙНОСТ (Дирихле), а не\r\n"
    "    # нулев поток. Операторът не запазваше колонния интеграл: измерено\r\n"
    "    # +294 % за 100 стъпки при K=0.05.\r\n"
    "    #\r\n"
    "    # Нулевият поток тук е коректен: обменът с повърхността минава\r\n"
    "    # отделно през SEB блока в step(), който внася H_sfc и E_dew\r\n"
    "    # консервативно в слоя DZ_EFF. Дифузията само преразпределя.\r\n"
    "    _r_p0 = K_int[0] * dt / ((z[1] - z[0]) * dz_full[0])\r\n"
    "    a[0]  = 0.0\r\n"
    "    b[0]  = 1.0 + _r_p0\r\n"
    "    c[0]  = -_r_p0\r\n"
    "\r\n"
    "    _r_mN = K_int[-1] * dt / ((z[-1] - z[-2]) * dz_full[-1])\r\n"
    "    a[-1] = -_r_mN\r\n"
    "    b[-1] = 1.0 + _r_mN\r\n"
    "    c[-1] = 0.0\r\n"
)

# ── Б. Консервативно внасяне на SEB ──────────────────────────────────
OLD_SEB = (
    "        _d_seb = H_sfc * self.dt / (self.rho[0] * cp * DZ_EFF_SEB)\r\n"
    "        T_new[0] += _d_seb\r\n"
    "\r\n"
    "        # Роса: изважда влага от приземното ниво\r\n"
    "        qv_new[0] -= E_dew * self.dt / (self.rho[0] * DZ_EFF_SEB)\r\n"
    "        qv_new[0] = max(qv_new[0], 1e-8)\r\n"
)
NEW_SEB = (
    "        # ── B2′: консервативно внасяне на повърхностния поток ──\r\n"
    "        # Беше: T_new[0] += H·dt/(ρ·cp·DZ_EFF) — ΔT, сметнато за слой\r\n"
    "        # DZ_EFF, приложено само върху клетка с дебелина dz_full[0]≈0.11m.\r\n"
    "        # Реално внесената енергия беше dz_full[0]/DZ_EFF ≈ 1.3 % от\r\n"
    "        # H·dt; останалото се доизмисляше от неконсервативната дифузия.\r\n"
    "        #\r\n"
    "        # Сега: същото ΔT върху ВСИЧКИ нива в слоя, нормирано по\r\n"
    "        # действителната му дебелина → внесена енергия = H·dt точно.\r\n"
    "        _lay = self.z <= DZ_EFF_SEB\r\n"
    "        if not np.any(_lay):\r\n"
    "            _lay = np.zeros_like(self.z, dtype=bool)\r\n"
    "            _lay[0] = True\r\n"
    "        _dz_lay = float(np.sum(self._dz_full[_lay]))\r\n"
    "\r\n"
    "        _d_seb = H_sfc * self.dt / (self.rho[0] * cp * _dz_lay)\r\n"
    "        T_new[_lay] += _d_seb\r\n"
    "\r\n"
    "        # Роса: изважда влага от слоя, също консервативно\r\n"
    "        qv_new[_lay] -= E_dew * self.dt / (self.rho[0] * _dz_lay)\r\n"
    "        qv_new[:] = np.maximum(qv_new, 1e-8)\r\n"
)

# ── В. Кеширане на dz_full ───────────────────────────────────────────
OLD_INIT = (
    "        # Диагностика\r\n"
    "        self.history  = []     # списък с dict за всеки изходен час\r\n"
)
NEW_INIT = (
    "        # B2\u2032: дебелини на контролните обеми — за консервативното\r\n"
    "        # внасяне на повърхностния поток. Същата формула като в\r\n"
    "        # turbulent_diffusion(), за да няма разминаване.\r\n"
    "        _dzd = np.diff(self.z)\r\n"
    "        self._dz_full = np.concatenate(\r\n"
    "            [[_dzd[0]], 0.5 * (_dzd[:-1] + _dzd[1:]), [_dzd[-1]]])\r\n"
    "\r\n"
    "        # Диагностика\r\n"
    "        self.history  = []     # списък с dict за всеки изходен час\r\n"
)

PATCHES = [
    ("гранични условия", OLD_BC,   NEW_BC),
    ("SEB внасяне",      OLD_SEB,  NEW_SEB),
    ("кеш dz_full",      OLD_INIT, NEW_INIT),
]

TEST = r'''
import numpy as np, fog_model as fm
z   = np.concatenate([np.geomspace(0.5,50,25), np.linspace(55,2000,20)])
dzf = np.concatenate([[np.diff(z)[0]], 0.5*(np.diff(z)[:-1]+np.diff(z)[1:]),
                      [np.diff(z)[-1]]])
rho = np.full(len(z),1.29); cp = 1005.0

def ratio(K0, n, DZ, H=-15.0):
    T = np.full(len(z),273.15+2.0) + np.minimum(z,200.)*0.020
    K = np.full(len(z),K0); I0 = float(np.sum(rho*cp*T*dzf))
    lay = z <= DZ; dz_lay = float(np.sum(dzf[lay]))
    for _ in range(n):
        T[lay] += H*60./(rho[0]*cp*dz_lay)
        T = fm.turbulent_diffusion(T,K,rho,z,60.)
    return (float(np.sum(rho*cp*T*dzf))-I0)/(H*60.*n)

bad = 0
print("  предадено/теоретично — трябва 1.000 навсякъде")
print(f"  {'DZ':>6}{'K':>8}{'30':>9}{'60':>9}{'180':>9}")
for DZ in (8.0, 50.0, 500.0):
    for K0 in (0.005, 0.03, 0.30):
        r = [ratio(K0,n,DZ) for n in (30,60,180)]
        bad += sum(1 for x in r if abs(x-1.0) > 5e-3)
        print(f"  {DZ:>6.0f}{K0:>8.3f}" + "".join(f"{x:>9.3f}" for x in r))
# нулев поток → замразен интеграл
p0 = np.where(z<5,10.,0.); p = p0.copy()
for _ in range(100):
    p = fm.turbulent_diffusion(p, np.full(len(z),0.05), rho, z, 60.)
drift = abs(float(np.sum(p*dzf)) - float(np.sum(p0*dzf))) / float(np.sum(p0*dzf))
print(f"  Дрейф при нулев поток: {drift*100:+.4f} %")
bad += (drift > 1e-6)
print("  РЕЗУЛТАТ:", "ВСИЧКО МИНАВА" if not bad else f"ПРОВАЛ ({bad})")
raise SystemExit(1 if bad else 0)
'''


def main():
    if not os.path.exists(PATH):
        sys.exit(f"[!] Няма {PATH} в текущата директория.")
    with io.open(PATH, "r", encoding="utf-8", newline="") as f:
        src = f.read()
    for name, old, _ in PATCHES:
        n = src.count(old)
        if n != 1:
            sys.exit(f"[!] '{name}': очаквах 1 съвпадение, намерих {n}. "
                     f"Върнат ли е файлът на B1-tke-stable? Нищо не е променено.")
    shutil.copy2(PATH, PATH + ".bak_B2p")
    for _, old, new in PATCHES:
        src = src.replace(old, new)
    with io.open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(src)
    print("[OK] 3 блока. Копие: fog_model.py.bak_B2p")
    print()
    print("── Приемателен тест на енергийния бюджет ──")
    rc = subprocess.call([sys.executable, "-c", TEST])
    if rc:
        print()
        print("[!] ТЕСТЪТ ПРОПАДА. Върни с:")
        print("    copy fog_model.py.bak_B2p fog_model.py")
        sys.exit(1)
    print()
    print("[!] ФИЗИКАТА Е ПРОМЕНЕНА — пусни пълния петлетищен гейт.")


if __name__ == "__main__":
    main()
