# -*- coding: utf-8 -*-
"""
patch_v18_no_shield.py  —  премахване на радиационния щит
==========================================================
ПРОМЕНЯ ФИЗИКАТА. Гейтът се пуска за двойката v17+v18 заедно.

Премахва блока, въведен на 19.07.2026:

    if lwp_col > 0.00005:
        _fog_top_idx = ...
        dQ_lw[:_fog_top_idx] = np.maximum(dQ_lw[:_fog_top_idx], -0.15/3600)

ЗАЩО СЕ МАХА
------------
Щитът е въведен срещу "нефизично разкъсване T_skin/T_air". Това
разкъсване имаше две причини, и двете вече отстранени:

  v16b — знакова грешка в SW поглъщането (слънцето охлаждаше мъглата
         вместо да я грее); при изгрев даваше −11 до −18 K/hr
  v17  — основата на F↑ излъчваше от T_въздух[0], не от T_skin, тоест
         липсваше отрицателната обратна връзка, която връща топлина
         на охлаждащия се въздух

Щитът лекуваше симптома на v17. С премахнати причини губи основанието
си и вече само вреди.

ЗАЩО ВРЕДИ
----------
Условието му е LWP (маса), а екранирането зависи от τ (оптическа
дебелина). При наблюдаваните LWP ~5e-5 kg/m² излиза τ_LW ≈ 0.007 —
мъглата е радиационно прозрачна и няма какво да екранира. Резултатът
е затворен кръг: мъглата не може да се сгъсти, защото щитът спира
охлаждането, което би я сгъстило.

Измерено (LBGO 2025-02-25, TERM_DEBUG):
    6.0h  LW = −0.15 K/hr   (is_fog=True,  щит активен)
    7.0h  LW = −0.80 K/hr   (is_fog=False, щит пада)
Един час разлика, същият профил — щитът реже 5.3 пъти.

ОЧАКВАНО СЛЕД ПРОМЯНАТА
-----------------------
max_cool остава единственият предпазител: сурово ≈ −2.3 K/hr се реже
на −0.80. Кондензацията връща ~42% като латентна топлина (при −6 °C,
dqsat/dT ≈ 0.17 g/kg/K), значи нетно ≈ −0.46 K/hr. За 6 часа мъгла:
≈2.8 K охлаждане, ≈0.5 g/kg кондензат, LWC ≈0.6 g/m³ → VIS ≈200 m.
Наблюдаваното при LBGO е 150–200 m.

Ако вместо това моделът произведе мъгла много под 100 m или T се
разкъса отново — диагнозата е грешна и се връщат и v17, и v18.

lwp_col се запазва: ползва се от max_cool по-долу.
"""
import io, os, shutil, sys

PATH = "fog_model.py"

OLD = (
    "    # ── Радиационно екраниране ВЪТРЕ в мъглата (19.07.2026) ──\r\n"
    "    # Консистентност със SEB is_fog фикса (праг 0.00005 kg/m²):\r\n"
    "    # SEB вече третира мъглата като черно тяло за T_skin; тук същото\r\n"
    "    # важи за въздушните нива ВЪТРЕ в мъгления слой. Физика (PAFOG):\r\n"
    "    # вътрешността на мъглата е радиационно екранирана — охлаждането\r\n"
    "    # се случва на ВЪРХА на мъглата, не вътре в нея. Без това моделната\r\n"
    "    # плитка мъгла (реално ~2m дълбока, LWP≈0.0001 → τ_LW≈0.015,\r\n"
    "    # прозрачна за многослойната схема) оставя T_air да се охлажда\r\n"
    "    # свободно, докато T_skin е стабилизирана → нефизично разкъсване\r\n"
    "    # T_skin/T_air (LBPD 2025-02-25: T_air −8.3°C при T_skin ~0°C).\r\n"
    "    # Вътре в мъглата: LW охлаждане ограничено до 0.15 K/hr.\r\n"
    "    if lwp_col > 0.00005:\r\n"
    "        _fog_mask = ql > 1e-6\r\n"
    "        if np.any(_fog_mask):\r\n"
    "            _fog_top_idx = int(np.max(np.where(_fog_mask)[0]))\r\n"
    "            _shield = -0.15 / 3600.0   # K/s\r\n"
    "            dQ_lw[:_fog_top_idx] = np.maximum(dQ_lw[:_fog_top_idx], _shield)\r\n"
    "    # ────────────────────────────────────────────────\r\n"
)

NEW = (
    "    # ── ПРЕМАХНАТО 27.07.2026: радиационен щит вътре в мъглата ──\r\n"
    "    # Беше:  if lwp_col > 0.00005:  dQ_lw[:fog_top] = max(dQ_lw, -0.15/3600)\r\n"
    "    #\r\n"
    "    # Въведен на 19.07 срещу разкъсване T_skin/T_air. И двете причини\r\n"
    "    # за онова разкъсване вече са отстранени:\r\n"
    "    #   v16b — знакът на SW поглъщането (слънцето охлаждаше мъглата)\r\n"
    "    #   v17  — F↑ в основата излъчва от T_skin, не от T_въздух[0];\r\n"
    "    #          това е отрицателната обратна връзка, която липсваше\r\n"
    "    #\r\n"
    "    # Освен това условието му беше по LWP (маса), докато екранирането\r\n"
    "    # зависи от τ. При реалните LWP ~5e-5 kg/m² τ_LW ≈ 0.007 — мъглата\r\n"
    "    # е радиационно прозрачна и няма какво да екранира. Получаваше се\r\n"
    "    # затворен кръг: мъглата не може да се сгъсти, защото щитът спира\r\n"
    "    # охлаждането, което би я сгъстило. Измерено при LBGO 2025-02-25:\r\n"
    "    # 6h LW=-0.15 (щит) срещу 7h LW=-0.80 (без щит) — реже 5.3 пъти.\r\n"
    "    #\r\n"
    "    # max_cool по-долу остава единственият предпазител.\r\n"
    "    # ────────────────────────────────────────────────\r\n"
)


def main():
    if not os.path.exists(PATH):
        sys.exit(f"[!] Няма {PATH} в текущата директория.")
    with io.open(PATH, "r", encoding="utf-8", newline="") as f:
        src = f.read()
    n = src.count(OLD)
    if n != 1:
        sys.exit(f"[!] Очаквах 1 съвпадение, намерих {n}. "
                 f"Приложена ли е v17? Прекратявам.")
    shutil.copy2(PATH, PATH + ".bak_v18")
    with io.open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(src.replace(OLD, NEW))
    print("[OK] Щитът е премахнат. Копие: fog_model.py.bak_v18")
    print("[!]  Пусни гейта за двойката v17+v18.")


if __name__ == "__main__":
    main()
