        src = loaded[path]
        for _, old, new in patches:
            src = src.replace(old, new)
        with io.open(path, "w", encoding="utf-8", newline="") as f:
            f.write(src)
        print(f"[OK] {path}  ({len(patches)} блок/а)  копие: {path}.bak_v19")

