# -*- coding: utf-8 -*-
"""
patch_B1_tke_stable.py  —  стабилизиране на TKE схемата
========================================================
ПРОМЕНЯ ФИЗИКАТА ДЪЛБОКО. Km и Kh влизат в дифузията на T, qv и ql,
тоест засяга всичко. Очаквай голямо движение в гейта.

Пипа САМО tke_step() в fog_model.py.

ДЕФЕКТ
------
Ред 356: e_new = e + dt * de_dt — напълно явен Ойлер върху уравнение
с два члена, чиито времеви мащаби са с порядъци под стъпката:

  дисипация  ε = Ce·e^1.5/l      τ = l/(Ce·√e) ≈ 0.36 s при z=0.5m
  дифузия    ∂/∂z(Km ∂e/∂z)      Km·dt/dz² ≈ 5·60/0.02 ≈ 15000

при dt = 60 s. Явната схема е нестабилна над dt/τ ≈ 2.

Резултатът е трептене през стъпка между пода и тавана (мерено
27.07.2026, V10 = 3 m/s, логаритмичен профил):

    стъпка 3: e[0]=10.00000    стъпка 4: e[0]=0.00001
    стъпка 5: e[0]= 8.53073    стъпка 6: e[0]=0.00001
    стъпка 7: e[0]= 8.52954    стъпка 8: e[0]=0.00001

Kh следва трептенето. Хибридът np.maximum(Km_tke, K_louis*0.1) в
step() и защитата срещу NaN на редове 811-815 са били въведени, за
да покрият именно това.

ПРОМЯНА
-------
1) Дисипацията полу-имплицитно. ε е линейна по e при замразено √e:

       e_new = (e + dt·P) / (1 + dt·Ce·√e/l)

   Безусловно устойчиво, стандартен подход при Mellor-Yamada.

2) Дифузията на TKE през turbulent_diffusion() — имплицитния Thomas
   решател, който вече е във файла и се ползва за T, qv и ql —
   вместо двата явни np.gradient.

ЕФЕКТ (тестван преди прилагане)
-------------------------------
Схемата се установява и за пръв път реагира на вятъра физически:

    V10 m/s   e[0]      Kh[0]      δ=√(2·Kh·3600)
      1.0    0.0092    0.00895        8.0 m
      2.0    0.0403    0.01902       11.7
      3.0    0.0931    0.02901       14.5
      4.5    0.2129    0.04393       17.8
      6.0    0.3812    0.05883       20.6
      8.0    0.6808    0.07867       23.8

e ∝ V², както изисква e ∝ u*². Изведената дифузионна дълбочина при
тихо е 8.0 m — точно зашитата в DZ_EFF константа 8.0. Физиката
възпроизвежда калибрираното в тихия предел.

ЗАБЕЛЕЖКА за v19 (отхвърлена 27.07): истинската зависимост на
дълбочината е √V. Отхвърлената кръпка ползваше V² по пориви — грешен
показател с четири степени, оттам CSI 0.369→0.275.

СЛЕДВА
------
B2: гранично условие на Нойман в turbulent_diffusion (сега Дирихле,
    z[0] е замразено спрямо турбулентен пренос — TERM показва
    дифуз=+0.00 на всеки ред)
B3: DZ_EFF от Kh вместо константите 8/50/500

Внимание: B1 сам по себе си може да влоши гейта. Km/Kh стават
по-малки и по-гладки, но z[0] още не ги получава заради Дирихле
условието. Двойката B1+B2 е физически една промяна.
"""
import io, os, shutil, sys

PATH = "fog_model.py"

OLD = (
    "    # Дисипация ε = Ce * e^(3/2) / l\r\n"
    "    eps = Ce * e * sq_e / np.maximum(l, 0.1)\r\n"
    "\r\n"
    "    # Дифузия на TKE: ∂/∂z(K_e * ∂e/∂z)  с K_e = Km\r\n"
    "    de_dz  = np.gradient(e, z)\r\n"
    "    flux_e = Km * de_dz * rho\r\n"
    "    diff_e = np.gradient(flux_e, z) / rho\r\n"
    "\r\n"
    "    # TKE уравнение\r\n"
    "    de_dt = P_shear + P_buoy - eps + diff_e\r\n"
    "    e_new = e + dt * de_dt\r\n"
)

NEW = (
    "    # ── B1 (27.07.2026): полу-имплицитна дисипация ──\r\n"
    "    # Беше: eps = Ce*e*sq_e/l ; e_new = e + dt*(P - eps + diff)\r\n"
    "    # Явният Ойлер е нестабилен: τ_дисип = l/(Ce·√e) ≈ 0.36 s при\r\n"
    "    # z=0.5m срещу dt=60 s. Схемата трептеше през стъпка между\r\n"
    "    # e_min=1e-5 и тавана 10, а Kh я следваше — беше шум, не сигнал.\r\n"
    "    #\r\n"
    "    # ε е линейна по e при замразено √e, затова:\r\n"
    "    #     e_new = (e + dt·P) / (1 + dt·Ce·√e/l)\r\n"
    "    # безусловно устойчиво (стандартно при Mellor-Yamada).\r\n"
    "    _sink = Ce * sq_e / np.maximum(l, 0.1)          # [1/s]\r\n"
    "    eps   = _sink * e                               # само за диагностика\r\n"
    "\r\n"
    "    # Източници без дифузията — тя се прилага отделно и имплицитно\r\n"
    "    _P = P_shear + P_buoy\r\n"
    "    e_new = (e + dt * _P) / (1.0 + dt * _sink)\r\n"
    "\r\n"
    "    # ── B1: дифузия на TKE през имплицитния Thomas решател ──\r\n"
    "    # Беше два явни np.gradient: Km·dt/dz² ≈ 15000 при най-финия\r\n"
    "    # слой (dz≈0.14m, Km до 5) — също катастрофално нестабилно.\r\n"
    "    e_new = turbulent_diffusion(np.maximum(e_new, e_min),\r\n"
    "                                Km, rho, z, dt)\r\n"
)


def main():
    if not os.path.exists(PATH):
        sys.exit(f"[!] Няма {PATH} в текущата директория.")
    with io.open(PATH, "r", encoding="utf-8", newline="") as f:
        src = f.read()
    n = src.count(OLD)
    if n != 1:
        sys.exit(f"[!] Очаквах 1 съвпадение, намерих {n}. "
                 f"Върнат ли е файлът на v18? Прекратявам.")
    shutil.copy2(PATH, PATH + ".bak_B1")
    with io.open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(src.replace(OLD, NEW))
    print("[OK] tke_step стабилизиран. Копие: fog_model.py.bak_B1")
    print("[!]  Km/Kh влизат в дифузията на T/qv/ql — очаквай голямо движение.")


if __name__ == "__main__":
    main()
