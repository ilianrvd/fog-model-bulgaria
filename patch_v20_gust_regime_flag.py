# -*- coding: utf-8 -*-
"""
patch_v20_gust_regime_flag.py  —  поривният режимен критерий за LBGO и LBPD
===========================================================================
Пипа ДВА файла: run_case.py и verify_cases.py. И двата в един diff —
урокът от v1.4, когато кръпката влезе само в единия и гейтът сертифицира
код, който не се е изпълнявал.

ЗАЩО
----
Поривният двоен критерий (v1.4, 26.07) досега работеше само при
крайбрежните, защото условието беше `cfg.get("coastal")`. Обосновката в
кода обаче е специфична за СОФИЙСКАТА КОТЛОВИНА — че ICON надценява
вятъра под инверсия — а е приложена към всички континентални летища.

Сух пробег 27.07 върху 264 случая (dryrun_gust_regime.py) показва, че
разграничението трябва да е друго:

    летище   HIT засегнати   FA засегнати
    LBGO         0.0 %          14.0 %      (11 от 11 HIT с нула часа)
    LBPD         0.0 %          10.2 %      ( 6 от  6 HIT с нула часа)
    LBSF        10.9 %           9.0 %      ← обратното съотношение

При Горна и Пловдив критерият не докосва нито един HIT. При София бие
повече по попаденията, отколкото по фалшивите тревоги.

ЗАЩО НЕ И СОФИЯ — С ПО-ВИСОК ПРАГ
---------------------------------
Решетъчен скан 27.07 (scan_lbsf_thresholds.py), V ∈ [4..8] kt ×
Gust ∈ [8..16] kt, критерий „>= 2 поредни часа":

    LBSF_CLDY_2024-01-19 е засегнат във ВСИЧКИТЕ 25 клетки,
    до V>=8 / Gust>=16 включително.

Ред с HIT = 0 и FA > 0 не съществува. Прагът не разделя, защото
величината не е свързана с приземното състояние: 2024-01-19 е точно
нощта, записана в кода от 01-19 като котловинен случай — ICON дава
>8 kt среден и >16 kt пориви 16 от 17 часа, а в реалността се е
образувала мъгла, която моделът е уловил. Горе духа, долу е тихо.

Затова София остава изключена, а въпросът ѝ отива в отворените теми
с друг предиктор (инверсионна сила от METAR, ΔT850), не с праг.

ПРОМЯНА
-------
Флаг `gust_regime` в AIRPORT_CONFIG вместо неявно ползване на
`coastal`. Условието в двата reassessment блока става
`cfg.get("gust_regime")`.

    LBWN, LBBG   gust_regime: True   (без промяна в поведението)
    LBGO, LBPD   gust_regime: True   (НОВО)
    LBSF         без флага           (без промяна в поведението)

`coastal` остава непокътнат — ползва се и за ADVECTIVE режима и за
sea_sector; не бива да се смесва с това.

ТОВА Е КРИТЕРИЙ, НЕ ФИЗИКА
--------------------------
Правилото не поправя уравнения — избира кога да им се вярва. Моделът
има известен дефект: импулсът не е прогностичен (u, v са замразени от
__init__), значи срезът никога не отслабва, турбулентността не може да
умре и приземна инверсия не се образува физически. Критерият заобикаля
това, като превключва на nudging при вятър.

При публикация да се описва като regime-selection heuristic с посочена
причина, НЕ като физически извод. Физическият дълг зад него —
прогностичен импулс с повърхностно триене — е в отворените теми.

ОЧАКВАНО
--------
CSI ≈ 0.39–0.40; нула загубени HIT при LBGO/LBPD; 3–5 FA → CN.
Критерият превключва режим и в 25 % от часовете на CN нощите, което
CSI не вижда — гейтът да се чете И по MAE_T регресиите.
"""
