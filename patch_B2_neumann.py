# -*- coding: utf-8 -*-
"""
patch_B2_neumann.py  —  истинско Нойманово гранично условие
============================================================
ПРОМЕНЯ ФИЗИКАТА ДЪЛБОКО. turbulent_diffusion() се ползва за T, qv,
ql и (след B1) за TKE. Засяга всичко.

Пипа САМО turbulent_diffusion() в fog_model.py.

ДЕФЕКТ
------
Редове 687-689:

    # Гранични условия (Neumann - нулев поток)
    b[0] = 1.0;  c[0] = 0.0
    a[-1] = 0.0; b[-1] = 1.0

Коментарът казва Нойман, кодът прави Дирихле. При a[0]=0, b[0]=1,
c[0]=0 и дясна страна d[0]=phi[0] ред нула на системата дава просто
phi_new[0] = phi[0] — стойността е ЗАМРАЗЕНА, не потокът е нулев.
Същото на върха.

ПОСЛЕДИЦА: операторът не запазва колонния интеграл. Замразеното
ниво работи като безкраен резервоар — храни съседа си вечно, без само
да се изчерпва. Измерено (100 стъпки чиста дифузия, K=0.05, начален
скок 10→0 при z=5m):

    Дирихле (сега)   интеграл 50.817 → 200.283     +294 %
    Нойман (B2)      интеграл 50.817 →  50.817     −0.00 %

Тоест дифузията ПРОИЗВЕЖДА топлина, влага и течна вода от нищото
винаги когато приземното ниво се различава от съседното.

КАКВО ОБЯСНЯВА
--------------
1) Влага. При ясна нощ qv[0] е близо до насищане, над него по-сухо.
   Замразеното qv[0] изпомпва влага нагоре безкрайно → колоната се
   насища без физически източник. Това е механизмът зад 24-те CDRY
   фалшиви тревоги (41 общо), където моделът е с +0.51 K ПО-ТОПЪЛ и
   въпреки това стига до 99.5 % RH.
   Съвпада с LBWN 2024-09-23: T точна до 0.2 K, консервираният qv
   изисква RH≈94 %, моделът обявява 99.5 %.

2) Температура. При инверсия T[0] < T[1]; замразеното студено ниво
   дърпа колоната надолу, без само да се стопля.

3) TERM диагностиката показваше дифуз=+0.00 на всеки ред — приземното
   ниво не получаваше нищо по турбулентен път, при това докато
   раздаваше на съседите.

ПРОМЯНА
-------
Крайните редове стават истински нулев поток през стените, с обмен
със съседното ниво (краен обем):

    r_p    = K_int[0]  · dt / ((z[1]-z[0]) · dz_full[0])
    b[0]   = 1 + r_p ;  c[0] = -r_p
    r_m    = K_int[-1] · dt / ((z[-1]-z[-2]) · dz_full[-1])
    b[-1]  = 1 + r_m ;  a[-1] = -r_m

Нулевият поток при дъното е коректен за ТОЗИ модел: обменът с
повърхността минава отделно през SEB (H_sfc / DZ_EFF), а дифузията
само преразпределя вътре в колоната.

ОЧАКВАНО
--------
FA надолу, най-вече CDRY. Приземният студен басейн се смекчава,
охлаждането може да се разпространи нагоре — възможно е мъглата да
се задълбочи. Но и обратното е възможно: по-слаб приземен максимум
на qv може да намали плътността. Гейтът ще каже.

ВНИМАНИЕ: това е поправка на коректността, не настройка. Дори гейтът
да се влоши, връщане към оператор, който не запазва маса, не е
защитимо. Ако числото падне, търсим какво друго е било калибрирано
срещу този дефект — както при щита.
"""
import io, os, shutil, sys

PATH = "fog_model.py"

OLD = (
    "    # Гранични условия (Neumann - нулев поток)\r\n"
    "    b[0] = 1.0;  c[0] = 0.0\r\n"
    "    a[-1] = 0.0; b[-1] = 1.0\r\n"
)

NEW = (
    "    # ── B2 (27.07.2026): ИСТИНСКИ Neumann — нулев поток през стените ──\r\n"
    "    # Беше:  b[0]=1; c[0]=0; a[-1]=0; b[-1]=1\r\n"
    "    # което при d[0]=phi[0] дава phi_new[0]=phi[0] — ЗАМРАЗЕНА\r\n"
    "    # СТОЙНОСТ (Дирихле), а не нулев поток. Операторът не запазваше\r\n"
    "    # колонния интеграл: замразеното ниво храни съседа си вечно.\r\n"
    "    # Мерено — 100 стъпки чиста дифузия: интеграл +294 %.\r\n"
    "    #\r\n"
    "    # Нулевият поток при дъното е коректен тук: обменът с\r\n"
    "    # повърхността минава отделно през SEB (H_sfc / DZ_EFF), а\r\n"
    "    # дифузията само преразпределя вътре в колоната.\r\n"
    "    _r_p0 = K_int[0] * dt / ((z[1] - z[0]) * dz_full[0])\r\n"
    "    a[0]  = 0.0\r\n"
    "    b[0]  = 1.0 + _r_p0\r\n"
    "    c[0]  = -_r_p0\r\n"
    "\r\n"
    "    _r_mN = K_int[-1] * dt / ((z[-1] - z[-2]) * dz_full[-1])\r\n"
    "    a[-1] = -_r_mN\r\n"
    "    b[-1] = 1.0 + _r_mN\r\n"
    "    c[-1] = 0.0\r\n"
)


def main():
    if not os.path.exists(PATH):
        sys.exit(f"[!] Няма {PATH} в текущата директория.")
    with io.open(PATH, "r", encoding="utf-8", newline="") as f:
        src = f.read()
    n = src.count(OLD)
    if n != 1:
        sys.exit(f"[!] Очаквах 1 съвпадение, намерих {n}. Прекратявам.")
    shutil.copy2(PATH, PATH + ".bak_B2")
    with io.open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(src.replace(OLD, NEW))
    print("[OK] Граничните условия поправени. Копие: fog_model.py.bak_B2")
    print("[!]  Засяга T, qv, ql и TKE. Пусни пълния петлетищен гейт.")


if __name__ == "__main__":
    main()
